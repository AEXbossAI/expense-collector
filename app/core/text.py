from __future__ import annotations

import re

# Postgres не принимает NUL в текстовых полях: asyncpg падает с
# CharacterNotInRepertoireError и роняет весь цикл разбора.
# Извлечение текста из PDF регулярно отдаёт \x00 и прочие управляющие
# символы — в документах встречаются шрифтовые артефакты и битые кодировки.
# Переводы строк и табуляцию оставляем: они несут структуру документа.
_CONTROL = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]")


def clean(value: str | None) -> str | None:
    """Текст, пригодный для записи в Postgres.

    Применяется ко ВСЕМУ, что пришло из документа или письма: извлечённый
    текст, тема, тело, имя вендора, назначение. Один NUL в любом из них
    останавливает разбор всего батча.
    """
    if value is None:
        return None
    return _CONTROL.sub("", value)
