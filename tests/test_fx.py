"""Пересчёт валют.

Направление курса — самая дорогая ошибка в этом коде: она тихая и
правдоподобная. ECB отдаёт «единиц валюты за 1 EUR», НБГ — «лари за 1
единицу валюты», направления противоположные. Каждый тест здесь закрепляет
именно направление, а не арифметику.

Числа взяты из живых проб 28.09.2026, а не придуманы.
"""

from __future__ import annotations

from datetime import date
from decimal import Decimal

import pytest

from app.services import fx


D = Decimal


# ── направление курса ─────────────────────────────────────────────────────


def test_ecb_считает_делением():
    """1770 ILS при 3.4812 шекеля за евро — это 508.45 EUR, не 6161."""
    assert fx.eur_from_ecb(D("1770"), D("3.4812")) == D("508.45")


def test_nbg_считает_кросс_курсом_через_лари():
    """7.90 AZN при 1.5343 лари за манат и 2.9927 лари за евро = 4.05 EUR.

    Живая проба: чек Bolt из Баку от 27.09.2026.
    """
    assert fx.eur_from_nbg(D("7.90"), D("1.5343"), D("2.9927")) == D("4.05")


def test_лари_считается_той_же_формулой_что_манат():
    """У самого GEL курс к лари равен единице, и формула вырождается в
    деление на курс евро. Отдельной ветки для лари нет намеренно: одна
    формула — один класс ошибок вместо двух.

    1720 GEL за печать рекламной продукции — это 574.73 EUR, а не 5147.
    """
    assert fx.eur_from_nbg(D("1720"), D("1"), D("2.9927")) == D("574.73")


def test_наружу_отдаётся_курс_за_один_евро():
    """Строка «4.90 AZN @ курс» должна объяснять сумму делением.

    Сырой курс НБГ — это лари за манат, и от него сумма не сходится:
    4.90 / 1.5343 = 3.19, а верный ответ 2.53. Эффективный курс
    2.9715 / 1.5343 = 1.93671...: 4.90 / 1.9367 = 2.53.
    """
    eff = fx.effective_rate(D("2.9715"), D("1.5343"))
    assert fx.eur_from_ecb(D("7.90"), eff) == fx.eur_from_nbg(D("7.90"), D("1.5343"), D("2.9715"))
    assert fx.eur_from_ecb(D("4.90"), eff) == D("2.53")


def test_для_лари_эффективный_курс_это_курс_евро():
    """У лари курс к лари равен единице, и эффективный вырождается
    в курс евро — ровно то, что стоит в строке «1720.00 GEL @ 2.9927»."""
    assert fx.effective_rate(D("2.9927"), D("1")) == D("2.9927")


def test_ноль_и_отрицательный_курс_не_проходят():
    """Курс 0 дал бы деление на ноль, отрицательный — отрицательный расход.
    Оба означают сломанный ответ провайдера, а не редкий случай."""
    with pytest.raises(ValueError):
        fx.eur_from_ecb(D("10"), D("0"))
    with pytest.raises(ValueError):
        fx.eur_from_nbg(D("10"), D("1"), D("-1"))


# ── разбор ответов провайдеров ────────────────────────────────────────────


def test_ecb_дата_берётся_из_ответа_а_не_из_запроса():
    """Провайдер сам откатывается на последний опубликованный день.
    Проверено: запрос на субботу 2026-09-19 вернул 2026-09-18.

    Если писать в fx_rate_date просимую дату, в базе окажется курс,
    которого в этот день не публиковали.
    """
    payload = {"amount": 1.0, "base": "EUR", "date": "2026-09-18",
               "rates": {"ILS": 3.4812, "USD": 1.146}}
    quote = fx.parse_ecb(payload, "ILS")
    assert quote is not None
    assert quote.rate == D("3.4812")
    assert quote.rate_date == date(2026, 9, 18)
    assert quote.source == fx.ECB


def test_ecb_отсутствие_валюты_в_наборе():
    """GEL и AZN в наборе ECB отсутствуют оба — проверено на живом
    /v1/currencies. Это не ошибка, это сигнал идти в НБГ."""
    assert fx.parse_ecb({"date": "2026-09-18", "rates": {"USD": 1.146}}, "GEL") is None


def test_nbg_читает_курс_и_дату():
    payload = [{
        "date": "2026-09-18T00:00:00.000Z",
        "currencies": [{"code": "EUR", "quantity": 1, "rate": 2.9927,
                        "validFromDate": "2026-09-18T00:00:00.000Z"}],
    }]
    quote = fx.parse_nbg(payload, "EUR")
    assert quote is not None
    assert quote.rate == D("2.9927")
    assert quote.rate_date == date(2026, 9, 18)
    assert quote.source == fx.NBG


def test_nbg_делит_на_quantity():
    """У слабых валют НБГ публикует курс за 100 или 1000 единиц. Без деления
    на quantity курс завышается в сто раз, и расход в йенах превращается
    в состояние."""
    payload = [{
        "date": "2026-09-18T00:00:00.000Z",
        "currencies": [{"code": "JPY", "quantity": 100, "rate": 1.8}],
    }]
    quote = fx.parse_nbg(payload, "JPY")
    assert quote is not None
    assert quote.rate == D("1.8") / D("100")


def test_nbg_не_путает_валюты():
    payload = [{
        "date": "2026-09-18T00:00:00.000Z",
        "currencies": [{"code": "USD", "quantity": 1, "rate": 2.71}],
    }]
    assert fx.parse_nbg(payload, "AZN") is None


def test_пустой_ответ_провайдера():
    assert fx.parse_nbg([], "EUR") is None
    assert fx.parse_ecb({}, "USD") is None


# ── нормализация кода валюты ──────────────────────────────────────────────


def test_код_валюты_приводится_к_верхнему_регистру():
    assert fx.normalize_currency("eur") == "EUR"
    assert fx.normalize_currency(" ils ") == "ILS"


def test_лари_у_нбг_не_спрашивают():
    """Лари — база НБГ, и на `?currencies=GEL` он отдаёт пустой массив.

    Регрессия 28.09.2026: без этой ветки грузинские расходы не
    пересчитывались вовсе и уехали бы на доску без суммы. Тест на формулу
    дыру не поймал, потому что подавал единицу прямо в неё; поймал сухой
    прогон на боевых данных.
    """
    assert fx.nbg_needs_request("GEL") is False
    assert fx.nbg_needs_request("AZN") is True
    assert fx.nbg_needs_request("EUR") is True


def test_нбг_на_запрос_лари_отдаёт_пустоту():
    """Форма ответа зафиксирована живой пробой: `[]`, а не ошибка."""
    assert fx.parse_nbg([], "GEL") is None


def test_мусор_вместо_валюты_отбраковывается():
    """Модель иногда возвращает символ вместо кода. Символ — не валюта,
    и курс по нему запрашивать нельзя."""
    for junk in (None, "", "€", "EURO", "12", "р."):
        assert fx.normalize_currency(junk) is None
